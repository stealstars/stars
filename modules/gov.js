  function buildUser(o) {
    const L = [];
    L.push('【这块地】');
    L.push('名字：' + (o.domain || '未命名'));
    if (o.scale) L.push('规模：' + o.scale);
    if (o.pop) L.push('人口：' + o.pop);
    if (o.treasury) L.push('金库：' + o.treasury);
    if (o.buildings) L.push('现有建筑：' + o.buildings + ' 处');

    // 建筑名能直接说明这地方有什么，比抽象数字有用得多
    if (o.buildingNames && o.buildingNames.length) {
      L.push('建筑：' + o.buildingNames.slice(0, 12).join('、')
        + (o.buildingNames.length > 12 ? ' 等 ' + o.buildingNames.length + ' 处' : ''));
    }

    if (o.faction) L.push('归属：' + o.faction + '（这是上级，不是本地的治理结构）');
    if (o.neighbours && o.neighbours.length) {
      L.push('周边：' + o.neighbours.join('、'));
    }

    L.push('');
    if (o.idea && o.idea.trim()) {
      L.push('玩家的诉求：' + o.idea.trim());
      L.push('');
      L.push('注意：如果这句里有「共产」「格式塔」「蜂巢」「铁腕」「民主」这类大词，'
        + '不要照搬名词，先按系统说明里的方式翻译成这块地上真实可做的事。');
    } else {
      L.push('玩家没有特别说明，请按这块地的实际条件给一套最合适的治理结构。');
    }
    L.push('');
    L.push('请为这块地产出一套治理结构。');
    return L.join('\n');
  }

  /* ------------------------------------------------------------ 解析 */

  function parse(text) {
    let s = String(text || '').trim();
    const fence = s.match(/```(?:json)?\s*([\s\S]*?)```/);
    if (fence) s = fence[1].trim();
    const i = s.indexOf('{');
    const j = s.lastIndexOf('}');
    if (i >= 0 && j > i) s = s.slice(i, j + 1);
    return JSON.parse(s);
  }

  function clip(v, n) {
    const t = String(v == null ? '' : v).replace(/\s+/g, ' ').trim();
    return t.length > n ? t.slice(0, n - 1) + '…' : t;
  }

