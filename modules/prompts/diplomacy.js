  /**
   * 模型偶尔不守规矩。这里把明显跑偏的地方当场纠正，
   * 免得界面上一堆「第7档·大型城市（原文标注…）」这种没法看的东西。
   */
  const TIER_NAMES = ['村庄', '小型村镇', '中型城镇', '大型城市', '超级城市', '小国或帝国行省', '大国'];

  /**
   * 归并到七档之一。认不出来的返回空串，绝不原样留着——
   * 留着「村」「小镇」「行省」这种，界面上就是一堆非标准档位，
   * 而且外交页会拿它去和七档表比对，比不中就没法显示升档参照。
   */
  function cleanTier(s) {
    const t = String(s || '').trim();
    if (!t) return '';
    // 长的先匹配，「小国或帝国行省」不能被「大国」抢走
    const order = TIER_NAMES.slice().sort((a, b) => b.length - a.length);
    for (const n of order) if (t.indexOf(n) >= 0) return n;

    // 常见简称：只认明确无歧义的
    const ALIAS = [
      [/^(村|村落|小村)$/, '村庄'],
      [/^(小镇|镇|集镇|乡镇)$/, '小型村镇'],
      [/^(城镇|城|县城)$/, '中型城镇'],
      [/^(城市|都城|大城)$/, '大型城市'],
      [/^(大都会|巨城|超大城市)$/, '超级城市'],
      [/^(行省|小国|公国|帝国行省)$/, '小国或帝国行省'],
      [/^(帝国|王国|大国|联邦)$/, '大国'],
    ];
    for (const [re, n] of ALIAS) if (re.test(t)) return n;
    return '';
  }

  function cleanEnum(s, allowed, fallback) {
    const t = String(s || '').trim();
    for (const a of allowed) if (t.indexOf(a) >= 0) return a;
    return fallback || '';
  }

  function clip(s, n) {
    const t = String(s == null ? '' : s).replace(/\s+/g, ' ').trim();
    return t.length > n ? t.slice(0, n) + '…' : t;
  }

