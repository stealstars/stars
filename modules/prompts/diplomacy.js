    out.治安 = cleanNum(out.治安);
    out.民心 = cleanNum(out.民心);

    out.人口 = clip(out.人口, 20);
    out.金库 = clip(out.金库, 20);
    out.月净额 = clip(out.月净额, 16);
    out.领地 = clip(out.领地, 24);
    out.所属势力 = clip(out.所属势力, 30);
    out.治理模式 = clip(out.治理模式, 40);

    if (out.军事.length > 3) out.军事 = out.军事.slice(0, 3);
    out.军事 = out.军事.map((u) => ({
      编制: clip(u && u.编制, 16),
      人数: clip(u && u.人数, 12),
      层级: clip(u && u.层级, 10),
    })).filter((u) => u.编制);

    if (out.营造.length > 5) out.营造 = out.营造.slice(0, 5);
    out.营造 = out.营造.map((b) => ({
      名: clip(b && b.名, 16),
      数量: clip(b && b.数量, 6),
      状态: clip(b && b.状态, 8),
    })).filter((b) => b.名);

    if (out.物产.length > 4) out.物产 = out.物产.slice(0, 4);
    out.物产 = out.物产.map((g) => ({
      名: clip(g && g.名, 16),
      数量: cleanEnum(g && g.数量, ['丰', '中', '少'], '中'),
      周期: cleanEnum(g && g.周期, ['月', '季', '年'], '月'),
      状态: clip(g && g.状态, 10),
    })).filter((g) => g.名);

