    /** 解析模型返回，容错：去代码块、取第一个 { 到最后一个 } */
    parse(text) {
      let s = String(text == null ? '' : text).trim();
      s = s.replace(/^```(?:json)?\s*/i, '').replace(/```\s*$/, '');
      const a = s.indexOf('{');
      const b = s.lastIndexOf('}');
      if (a < 0 || b <= a) throw new Error('返回里没有 JSON 对象');
      return JSON.parse(s.slice(a, b + 1));
    },
